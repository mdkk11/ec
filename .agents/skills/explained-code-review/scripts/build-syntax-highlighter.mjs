import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const directory = dirname(fileURLToPath(import.meta.url))
const source = join(directory, 'syntax-highlighter.source.mjs')
const output = join(directory, 'syntax-highlighter.bundle.mjs')
const sourceHash = createHash('sha256')
  .update(readFileSync(source))
  .digest('hex')

await build({
  entryPoints: [source],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  legalComments: 'eof',
  minifySyntax: true,
  banner: {
    js: `// @generated by build-syntax-highlighter.mjs; do not edit; Shiki 4.3.1; source-sha256 ${sourceHash}`,
  },
})
